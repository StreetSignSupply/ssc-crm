import { initializeTestEnvironment, assertFails, assertSucceeds } from "@firebase/rules-unit-testing";
import { doc, getDoc, setDoc, updateDoc, deleteDoc } from "firebase/firestore";
import fs from "node:fs";
const env = await initializeTestEnvironment({ projectId: "demo-ssc", firestore: { rules: fs.readFileSync(new URL("./firestore.rules", import.meta.url), "utf8"), host: "127.0.0.1", port: 8080 } });
await env.withSecurityRulesDisabled(async (c) => { const d = c.firestore();
  await setDoc(doc(d, "access/matt@streetsignsupply.com"), { role: "owner", teamId: "t1" });
  await setDoc(doc(d, "access/bob@streetsignsupply.com"), { role: "sales", teamId: "t2" });
  await setDoc(doc(d, "access/uid-shop"), { role: "shop", teamId: "t3" });
  await setDoc(doc(d, "team/t2"), { name: "Bob", access: "sales", phone: "1", email: "bob@streetsignsupply.com" });
  await setDoc(doc(d, "team/t1"), { name: "Matt", access: "owner", email: "matt@streetsignsupply.com" });
  await setDoc(doc(d, "settings/secrets"), { shopToken: "x" }); await setDoc(doc(d, "settings/syncsent"), { a: 1 });
  await setDoc(doc(d, "items/i1"), { name: "sheet", cost: "1", onHand: 2 }); await setDoc(doc(d, "history/h2"), { entries: [1, 2, 3] });
  await setDoc(doc(d, "projects/p1"), { name: "x" }); await setDoc(doc(d, "settings/brand"), { a: 1 }); await setDoc(doc(d, "history/h1"), { entries: [] }); });
const as = (uid, email) => env.authenticatedContext(uid, email ? { email, email_verified: true } : {}).firestore();
const owner = as("u1", "MATT@streetsignsupply.com"), sales = as("u2", "bob@streetsignsupply.com"), shop = as("uid-shop"), outsider = as("u9", "someone@gmail.com"), anon = env.unauthenticatedContext().firestore();
const unverified = env.authenticatedContext("u8", { email: "bob@streetsignsupply.com", email_verified: false }).firestore();
const t = []; const ok = async (n, p) => { try { await assertSucceeds(p); t.push("PASS " + n); } catch (e) { t.push("FAIL " + n + " " + e.message.slice(0, 80)); } };
const no = async (n, p) => { try { await assertFails(p); t.push("PASS " + n); } catch (e) { t.push("FAIL " + n); } };
await no("anonymous can't read", getDoc(doc(anon, "projects/p1")));
await no("outsider can't read", getDoc(doc(outsider, "projects/p1")));
await no("outsider can't write", setDoc(doc(outsider, "projects/p2"), { a: 1 }));
await no("unverified email can't read", getDoc(doc(unverified, "projects/p1")));
await ok("owner reads (email any case)", getDoc(doc(owner, "projects/p1")));
await ok("sales reads", getDoc(doc(sales, "projects/p1")));
await ok("shop (by sign-in id) reads", getDoc(doc(shop, "projects/p1")));
await ok("sales edits a project", updateDoc(doc(sales, "projects/p1"), { name: "y" }));
await no("sales can't hard-delete", deleteDoc(doc(sales, "projects/p1")));
await no("shop can't hard-delete", deleteDoc(doc(shop, "projects/p1")));
await no("sales can't change settings", updateDoc(doc(sales, "settings/brand"), { a: 2 }));
await ok("owner changes settings", updateDoc(doc(owner, "settings/brand"), { a: 3 }));
await no("sales can't raise own access", updateDoc(doc(sales, "team/t2"), { access: "owner" }));
await ok("sales updates own phone", updateDoc(doc(sales, "team/t2"), { phone: "2" }));
await no("sales can't write the access list", setDoc(doc(sales, "access/bob@streetsignsupply.com"), { role: "owner" }));
await ok("owner sets a level", updateDoc(doc(owner, "team/t2"), { access: "office" }));
await no("sales can't delete history", deleteDoc(doc(sales, "history/h1")));
await ok("sales adds history", updateDoc(doc(sales, "history/h1"), { entries: [1] }));
await no("sales can't edit someone else's team record", updateDoc(doc(sales, "team/t1"), { phone: "9" }));
await no("sales can't read the secrets", getDoc(doc(sales, "settings/secrets")));
await ok("owner reads the secrets", getDoc(doc(owner, "settings/secrets")));
await ok("shop records what's been sent to the sheet", updateDoc(doc(shop, "settings/syncsent"), { a: 2 }));
await no("history can't be cut short", updateDoc(doc(sales, "history/h2"), { entries: [1] }));
await no("shop can't change quote prices", updateDoc(doc(shop, "projects/p1"), { orderLines: [] }));
await ok("shop moves a project note", updateDoc(doc(shop, "projects/p1"), { notes: "x" }));
await no("sales can't change an item's cost", updateDoc(doc(sales, "items/i1"), { cost: "2" }));
await ok("shop counts stock", updateDoc(doc(shop, "items/i1"), { onHand: 3 }));
await ok("owner changes an item's cost", updateDoc(doc(owner, "items/i1"), { cost: "3" }));
await ok("shop adds a stock move", setDoc(doc(shop, "invtx/x1"), { qty: 1 }));
await no("shop can't delete a stock move", deleteDoc(doc(shop, "invtx/x1")));
await ok("owner hard-deletes", deleteDoc(doc(owner, "projects/p1")));
console.log(t.join("\n")); await env.cleanup(); process.exit(t.some((x) => x.startsWith("FAIL")) ? 1 : 0);
